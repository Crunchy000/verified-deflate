//! A stand-in for the `kani` crate that runs proof harnesses as randomised
//! tests. **This is not verification**: it samples inputs instead of
//! exploring all of them. It exists so harnesses can be compiled and
//! smoke-tested on machines without Kani; `cargo kani` is the real check.
//!
//! Each harness runs `KANI_SAMPLE_ITERS` times (default 3000). Values from
//! [`any`] are biased towards small numbers and boundary values so that
//! typical `kani::assume` constraints are satisfied often. Runs whose
//! assumptions fail are discarded. Set `KANI_SAMPLE_SEED` to vary inputs.

use std::cell::Cell;
use std::panic::{self, AssertUnwindSafe};
use std::sync::Once;

pub use kani_sample_macros::{proof, solver, stub, unwind};

/// Panic payload used to abandon a run whose assumptions do not hold.
struct AssumptionFailed;

thread_local! {
    static STATE: Cell<u64> = const { Cell::new(0x9E37_79B9_7F4A_7C15) };
}

fn next_u64() -> u64 {
    STATE.with(|s| {
        // xorshift64*
        let mut x = s.get();
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        s.set(x);
        x.wrapping_mul(0x2545_F491_4F6C_DD1D)
    })
}

/// Types that can be generated by [`any`].
pub trait Arbitrary: Sized {
    /// Produces a value.
    fn any() -> Self;
}

macro_rules! impl_int {
    ($($t:ty),*) => {$(
        impl Arbitrary for $t {
            fn any() -> Self {
                let r = next_u64();
                match r % 16 {
                    // small non-negative values
                    0..=4 => ((r >> 8) % 17) as $t,
                    // values at the top of the range
                    5..=6 => <$t>::MAX.wrapping_sub(((r >> 8) % 4) as $t),
                    // the bottom of the range (negative for signed types)
                    7 => <$t>::MIN.wrapping_add(((r >> 8) % 4) as $t),
                    // a power of two, possibly off by one
                    8..=9 => {
                        let bits = <$t>::BITS as u64;
                        let p = (1 as $t).wrapping_shl(((r >> 8) % bits) as u32);
                        p.wrapping_add((((r >> 16) % 3) as $t).wrapping_sub(1 as $t))
                    }
                    // anything
                    _ => (r >> 3) as $t,
                }
            }
        }
    )*};
}
impl_int!(u8, u16, u32, u64, u128, usize, i8, i16, i32, i64, i128, isize);

impl Arbitrary for bool {
    fn any() -> Self {
        next_u64() & 1 == 1
    }
}

impl<T: Arbitrary, const N: usize> Arbitrary for [T; N] {
    fn any() -> Self {
        core::array::from_fn(|_| T::any())
    }
}

impl<T: Arbitrary> Arbitrary for Option<T> {
    fn any() -> Self {
        if bool::any() { Some(T::any()) } else { None }
    }
}

/// A value of type `T` (random here; every value under real Kani).
pub fn any<T: Arbitrary>() -> T {
    T::any()
}

/// A value satisfying `f` (retries, then abandons the run).
pub fn any_where<T: Arbitrary, F: Fn(&T) -> bool>(f: F) -> T {
    for _ in 0..64 {
        let v = T::any();
        if f(&v) {
            return v;
        }
    }
    panic::panic_any(AssumptionFailed)
}

/// Abandons the current run unless `cond` holds.
pub fn assume(cond: bool) {
    if !cond {
        panic::panic_any(AssumptionFailed);
    }
}

/// Kani's coverage marker; a no-op here.
#[macro_export]
macro_rules! cover {
    ($($t:tt)*) => {};
}

fn install_hook() {
    static ONCE: Once = Once::new();
    ONCE.call_once(|| {
        let default = panic::take_hook();
        panic::set_hook(Box::new(move |info| {
            if info.payload().downcast_ref::<AssumptionFailed>().is_none() {
                default(info);
            }
        }));
    });
}

fn hash(s: &str) -> u64 {
    s.bytes().fold(0xcbf2_9ce4_8422_2325, |h, b| (h ^ u64::from(b)).wrapping_mul(0x0100_0000_01b3))
}

#[doc(hidden)]
pub fn __run(name: &str, harness: fn()) {
    install_hook();
    let iters: u64 = std::env::var("KANI_SAMPLE_ITERS").ok().and_then(|v| v.parse().ok()).unwrap_or(3000);
    let seed: u64 = std::env::var("KANI_SAMPLE_SEED").ok().and_then(|v| v.parse().ok()).unwrap_or(1);
    let mut accepted = 0u64;
    for i in 0..iters {
        let s = hash(name) ^ seed.wrapping_mul(0x9E37_79B9_7F4A_7C15) ^ i.wrapping_mul(0xD1B5_4A32_D192_ED03);
        STATE.with(|st| st.set(s | 1));
        match panic::catch_unwind(AssertUnwindSafe(harness)) {
            Ok(()) => accepted += 1,
            Err(p) if p.downcast_ref::<AssumptionFailed>().is_some() => {}
            Err(p) => {
                eprintln!("harness {name} failed on iteration {i} (KANI_SAMPLE_SEED={seed})");
                panic::resume_unwind(p);
            }
        }
    }
    assert!(
        accepted * 100 >= iters,
        "harness {name}: only {accepted}/{iters} runs satisfied its assumptions; the sample is too thin"
    );
}
